import { launchShell } from './lib.mjs';
const theme = process.argv[2] || 'light';
const lang = process.argv[3] || 'en';
const s = await launchShell({ theme, lang, settings: { wallpaperMode: 'animated' } });
const A = (fn, a) => s.aurora(fn, a);
const go = async (page, section) => {
  await A(({ page, section }) => window.__aurora.shell.launch('settings', { page, section }), { page, section });
  await s.page.waitForTimeout(1500);
};
await go('background');
await A(() => { const w = window.__aurora.wm.byApp('settings')[0]; w.maximize(); });
await s.page.waitForTimeout(1200);
await s.shot(`wpui-background-${theme}-${lang}`);
await go('wallpaperEffects');
await s.page.waitForTimeout(800);
await s.shot(`wpui-effects-${theme}-${lang}`);
await A(() => document.querySelector('.app-settings .st-scroll').scrollTop = 900);
await s.page.waitForTimeout(800);
await s.shot(`wpui-effects2-${theme}-${lang}`);
await go('lockscreen');
await s.shot(`wpui-lock-${theme}-${lang}`);
console.log('errors', s.logs.filter((l) => /error|pageerror/i.test(l)).slice(0, 10));
await s.close();
