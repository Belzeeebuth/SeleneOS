import { launchShell } from './lib.mjs';
import fs from 'node:fs';
const kind = process.argv[2] || 'rain';
const codes = { rain: 63, snow: 73, storm: 95, fog: 45, clouds: 3, clear: 0 };
const mock = '/tmp/claude-0/scratch/wx-mock.json';
fs.writeFileSync(mock, JSON.stringify({ current: { weather_code: codes[kind], is_day: 1, temperature_2m: 11.4, time: '2026-10-10T14:00' } }));
const s = await launchShell({ theme: 'light', env: { AURORA_WEATHER_MOCK: mock }, settings: { wallpaperMode: 'dynamic', dynamicWallpaper: { source: 'weather', set: process.argv[3] || 'lake', location: { name: 'Paris', lat: 48.8566, lon: 2.3522 } } } });
const A = (fn, a) => s.aurora(fn, a);
await A(() => window.__aurora.wallpaperEngine.setClock(new Date('2026-10-10T13:00:00')));
await s.page.waitForTimeout(2500);
console.log(JSON.stringify(await A(() => { const x = window.__aurora.wallpaperEngine.state; return { dyn: x.dynamic, w: x.weather && { kind: x.weather.kind, d: x.weather.describe }, fx: x.weatherFx, err: x.weatherError }; })));
await s.shot(`wp-probe-weather-${kind}`);
console.log('errors', s.logs.filter((l) => /error|pageerror/i.test(l)).slice(0, 10));
await s.close();
